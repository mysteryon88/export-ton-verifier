import test from "node:test";
import assert from "node:assert/strict";
import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";
import ejs from "ejs";
import { Address, beginCell, Cell, toNano } from "@ton/core";
import { Blockchain, createShardAccount } from "@ton/sandbox";
import { runTolkCompiler } from "@ton/tolk-js";
import { g1Compressed, g2Compressed, getCurveFromName } from "../src/utils.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const templatePath = path.join(
  __dirname,
  "../templates/tolk_verifier_plonk.ejs",
);

const dummyG1 = "a0" + "11".repeat(47);
const dummyG2 = "b0" + "22".repeat(95);
const dummyG1Uncompressed = "c0" + "33".repeat(95);

async function renderTemplate(nPublic, contractName, constants = {}) {
  const template = await fs.readFile(templatePath, "utf8");
  return ejs.render(template, {
    protocol: "plonk",
    curve: "bls12381",
    contractName,
    nPublic,
    power: 4,
    k1: "5",
    k2: "7",
    w: "13",
    Qm: constants.g1 ?? dummyG1,
    Ql: constants.g1 ?? dummyG1,
    Qr: constants.g1 ?? dummyG1,
    Qo: constants.g1 ?? dummyG1,
    Qc: constants.g1 ?? dummyG1,
    S1: constants.g1 ?? dummyG1,
    S2: constants.g1 ?? dummyG1,
    S3: constants.g1 ?? dummyG1,
    X_2: constants.g2 ?? dummyG2,
    Qm_uc: constants.g1Uc ?? dummyG1Uncompressed,
    Ql_uc: constants.g1Uc ?? dummyG1Uncompressed,
    Qr_uc: constants.g1Uc ?? dummyG1Uncompressed,
    Qo_uc: constants.g1Uc ?? dummyG1Uncompressed,
    Qc_uc: constants.g1Uc ?? dummyG1Uncompressed,
    S1_uc: constants.g1Uc ?? dummyG1Uncompressed,
    S2_uc: constants.g1Uc ?? dummyG1Uncompressed,
    S3_uc: constants.g1Uc ?? dummyG1Uncompressed,
  });
}

test("renders PLONK verifier as Tolk contract instead of FunC", async () => {
  const rendered = await renderTemplate(2);

  assert.match(rendered, /contract Verifier \{\s*description: "PLONK verifier generated by export-ton-verifier"\s*storage: VerifierStorage\s*incomingMessages: VerifyProofMessage\s*\}/);
  assert.match(rendered, /struct VerifierStorage \{\}/);
  assert.match(rendered, /type ScalarArray = array<uint256>/);
  assert.match(rendered, /type G1Compressed = bits384/);
  assert.match(rendered, /type G1Uncompressed = bits768/);
  assert.match(rendered, /struct \(0x76524659\) VerifyProofMessage \{\s*proof: Cell<VerifyProofPayload>\s*\}/);
  assert.match(rendered, /struct VerifyProofPayload \{\s*compressed: Cell<CompressedProof>\s*evaluations: Cell<EvaluationValues>\s*publicInputs: ScalarArray\s*uncompressed: Cell<UncompressedProof>\s*\}/);
  assert.match(rendered, /struct CompressedProof \{\s*ab: Cell<CompressedPair>\s*cz: Cell<CompressedPair>\s*t12: Cell<CompressedPair>\s*tail: Cell<CompressedTail>\s*\}/);
  assert.match(rendered, /struct UncompressedProof \{\s*a: Cell<G1Uncompressed>\s*b: Cell<G1Uncompressed>\s*c: Cell<G1Uncompressed>\s*tail: Cell<UncompressedTail>\s*\}/);
  assert.match(rendered, /enum VerifierErrors \{\s*PublicNotPresent = 101,\s*FailedInverse = 102,\s*ScalarNotInField = 103,\s*TooManyPublics = 104,\s*InvalidMessage = 105,\s*InvalidProof = 106,\s*NotEnoughValue = 107,\s*\}/);
  assert.match(rendered, /const QM: slice = "[a-f0-9]+".hexToSlice\(\)/);
  assert.match(rendered, /@pure\s+fun blsPairing\(/);
  assert.match(rendered, /fun int\.scalarToSlice\(self\): slice/);
  assert.match(rendered, /fun G1Compressed\.asSlice\(self\): slice/);
  assert.match(rendered, /fun G1Uncompressed\.asSlice\(self\): slice/);
  assert.match(rendered, /fun ScalarArray\.read\(self, i: int\): int/);
  assert.match(rendered, /fun ScalarArray\.setAt\(mutate self, i: int, v: int\): void/);
  assert.match(rendered, /fun checkPublicInputCount\(publicInputs: ScalarArray, nExpected: int\): void/);
  assert.match(rendered, /fun verifyFromPayload\(payload: VerifyProofPayload\): bool/);
  assert.match(rendered, /return verify\(\s*ab\.first\.asSlice\(\), ab\.second\.asSlice\(\), cz\.first\.asSlice\(\), cz\.second\.asSlice\(\),/);
  assert.match(rendered, /get fun verify\(/);
  assert.match(rendered, /publicInputs: ScalarArray/);
  assert.match(rendered, /checkField\(evalA\);/);
  assert.match(rendered, /while \(newr != 0\)/);
  assert.match(rendered, /while \(pi < N_PUBLIC\)/);
  assert.match(rendered, /betaHash\.push\(publicInputs\.read\(pi\)\.scalarToSlice\(\)\);/);
  assert.match(rendered, /checkPublicInputCount\(publicInputs, N_PUBLIC\);/);
  assert.match(rendered, /val evalL1: int = mulmod\(invd\.read\(1\), zh, blsR\(\)\);/);
  assert.doesNotMatch(rendered, /var evalL1: int/);
  assert.match(rendered, /return blsPairing\(blsG1Neg\(a1\), X_2, b1, BLS_G2\) != 0;/);
  assert.match(rendered, /fun onInternalMessage\(inMsg: InMessage\)/);
  assert.match(rendered, /VerifyProofMessage\.fromSlice\(inMsg\.body, \{ throwIfOpcodeDoesNotMatch: VerifierErrors\.InvalidMessage \}\)/);
  assert.match(rendered, /assert \(verifyFromPayload\(msg\.proof\.load\(\)\)\) throw VerifierErrors\.InvalidProof;/);

  assert.doesNotMatch(rendered, /#include/);
  assert.doesNotMatch(rendered, /verifier::/);
  assert.doesNotMatch(rendered, /bls::/);
  assert.doesNotMatch(rendered, /recv_internal/);
  assert.doesNotMatch(rendered, /method_id/);
  assert.doesNotMatch(rendered, /throw\(/);
  assert.doesNotMatch(rendered, /ScalarMap/);
  assert.doesNotMatch(rendered, /map<uint32, uint256>/);
});

test("documents safety requirements for every PLONK Tolk asm helper", async () => {
  const rendered = await renderTemplate(2);
  const lines = rendered.split(/\r?\n/);

  for (const helper of [
    "blsPairing",
    "keccak256Tuple",
    "blsR",
    "mulmod",
    "blsG1Add",
    "blsG1Mul",
    "blsG1Sub",
    "blsG1Neg",
  ]) {
    const helperLine = lines.findIndex((line) =>
      line.includes(`fun ${helper}(`) && line.includes(' asm "'),
    );
    assert.notEqual(helperLine, -1, `${helper} asm declaration should render`);
    assert.match(
      lines.slice(Math.max(0, helperLine - 4), helperLine).join("\n"),
      /\/\/\/ # Safety/,
      `${helper} should have a nearby # Safety doc comment before its asm declaration`,
    );
  }
});

test("renders named PLONK contract metadata when contractName is provided", async () => {
  const rendered = await renderTemplate(0, "SecondVerifier");

  assert.match(rendered, /contract SecondVerifier \{\s*description: "PLONK verifier generated by export-ton-verifier"\s*storage: SecondVerifierStorage\s*incomingMessages: VerifyProofMessage\s*\}/);
  assert.match(rendered, /struct SecondVerifierStorage \{\}/);
  assert.match(rendered, /enum SecondVerifierErrors \{/);
  assert.match(rendered, /throw SecondVerifierErrors\.FailedInverse;/);
  assert.match(rendered, /VerifyProofMessage\.fromSlice\(inMsg\.body, \{ throwIfOpcodeDoesNotMatch: SecondVerifierErrors\.InvalidMessage \}\)/);
  assert.match(rendered, /assert \(verifyFromPayload\(msg\.proof\.load\(\)\)\) throw SecondVerifierErrors\.InvalidProof;/);
  assert.match(rendered, /const N_PUBLIC: int = 0/);
  assert.match(rendered, /const N_LAGRANGE: int = 1/);
  assert.match(rendered, /get fun verify\(/);
  assert.doesNotMatch(rendered, /get fun verify_SecondVerifier/);
});

test("Tolk PLONK runtime rejects identity and non-subgroup points from raw inputs", async () => {
  const curve = await getCurveFromName("bls12381");
  try {
    const g1Point = curve.G1.toObject(curve.G1.g);
    const g1 = g1Compressed(curve, g1Point);
    const g2 = g2Compressed(curve, curve.G2.toObject(curve.G2.g));
    const g1UcBytes = new Uint8Array(96);
    curve.G1.toRprUncompressed(
      g1UcBytes,
      0,
      curve.G1.fromObject(g1Point),
    );
    const g1Uc = Buffer.from(g1UcBytes).toString("hex");
    const source = await renderTemplate(0, undefined, { g1, g2, g1Uc });
    const compiled = await runTolkCompiler({
      entrypointFileName: "VerifierPlonkRuntime.tolk",
      fsReadCallback: () => source,
    });
    assert.equal(
      compiled.status,
      "ok",
      compiled.status === "error" ? compiled.message : undefined,
    );
    if (compiled.status !== "ok") return;

    const code = Cell.fromBoc(Buffer.from(compiled.codeBoc64, "base64"))[0];
    const address = new Address(0, Buffer.alloc(32, 2));
    const blockchain = await Blockchain.create();
    blockchain.verbosity = {
      print: false,
      blockchainLogs: false,
      vmLogs: "none",
      debugLogs: false,
    };
    await blockchain.setShardAccount(
      address,
      createShardAccount({
        address,
        code,
        data: beginCell().endCell(),
        balance: toNano("1"),
      }),
    );

    const point = (hex) =>
      beginCell().storeBuffer(Buffer.from(hex, "hex")).endCell();
    const validG1 = point(g1);
    const validG1Uc = point(g1Uc);
    const identity = point(
      g1Compressed(curve, curve.G1.toObject(curve.G1.zero)),
    );
    const nonSubgroupPoint = curve.G1.fromObject([0n, 2n, 1n]);
    assert.equal(curve.G1.isValid(nonSubgroupPoint), true);
    assert.equal(
      curve.G1.isZero(curve.G1.timesScalar(nonSubgroupPoint, curve.r)),
      false,
    );
    const nonSubgroup = point(g1Compressed(curve, [0n, 2n, 1n]));
    const validProofPoints = Array(9).fill(validG1);
    const args = (proofPoints = validProofPoints) => [
      ...proofPoints.slice(0, 7).map((cell) => ({ type: "slice", cell })),
      ...[1n, 2n, 3n, 4n, 5n, 6n].map((value) => ({ type: "int", value })),
      { type: "slice", cell: proofPoints[7] },
      { type: "slice", cell: proofPoints[8] },
      { type: "tuple", items: [] },
      ...Array.from({ length: 9 }, () => ({ type: "slice", cell: validG1Uc })),
    ];
    const rejectsInvalidProof = async (promise) => {
      await assert.rejects(promise, (error) => error?.exitCode === 106);
    };

    const validResult = await blockchain.runGetMethod(address, "verify", args());
    assert.equal(validResult.exitCode, 0);
    for (const hostilePoint of [identity, nonSubgroup]) {
      for (let pointIndex = 0; pointIndex < validProofPoints.length; pointIndex += 1) {
        const proofPoints = [...validProofPoints];
        proofPoints[pointIndex] = hostilePoint;
        await rejectsInvalidProof(
          blockchain.runGetMethod(address, "verify", args(proofPoints)),
        );
      }
    }

    const pair = (first, second) =>
      beginCell()
        .storeSlice(first.beginParse())
        .storeSlice(second.beginParse())
        .endCell();
    const rawBody = (proofPoints) => {
      const compressedTail = beginCell()
        .storeRef(pair(proofPoints[6], proofPoints[7]))
        .storeRef(proofPoints[8])
        .endCell();
      const compressed = beginCell()
        .storeRef(pair(proofPoints[0], proofPoints[1]))
        .storeRef(pair(proofPoints[2], proofPoints[3]))
        .storeRef(pair(proofPoints[4], proofPoints[5]))
        .storeRef(compressedTail)
        .endCell();
      const evaluations = beginCell()
        .storeRef(
          beginCell().storeUint(1, 256).storeUint(2, 256).storeUint(3, 256),
        )
        .storeRef(
          beginCell().storeUint(4, 256).storeUint(5, 256).storeUint(6, 256),
        )
        .endCell();
      const uncompressedTail2 = beginCell()
        .storeRef(validG1Uc)
        .storeRef(validG1Uc)
        .storeRef(validG1Uc)
        .endCell();
      const uncompressedTail = beginCell()
        .storeRef(validG1Uc)
        .storeRef(validG1Uc)
        .storeRef(validG1Uc)
        .storeRef(uncompressedTail2)
        .endCell();
      const uncompressed = beginCell()
        .storeRef(validG1Uc)
        .storeRef(validG1Uc)
        .storeRef(validG1Uc)
        .storeRef(uncompressedTail)
        .endCell();
      const payload = beginCell()
        .storeRef(compressed)
        .storeRef(evaluations)
        .storeUint(0, 8)
        .storeBit(false)
        .storeRef(uncompressed)
        .endCell();
      return beginCell().storeUint(0x76524659, 32).storeRef(payload).endCell();
    };
    const sender = await blockchain.treasury("plonk-point-sender");
    for (const hostilePoint of [identity, nonSubgroup]) {
      for (let pointIndex = 0; pointIndex < validProofPoints.length; pointIndex += 1) {
        const proofPoints = [...validProofPoints];
        proofPoints[pointIndex] = hostilePoint;
        const sent = await sender.send({
          to: address,
          value: toNano("0.1"),
          body: rawBody(proofPoints),
        });
        const target = sent.transactions.find(
          (transaction) =>
            transaction.inMessage?.info.type === "internal" &&
            transaction.inMessage.info.dest.equals(address),
        );
        assert.equal(target?.description.type, "generic");
        assert.equal(target?.description.computePhase.type, "vm");
        assert.equal(target.description.computePhase.exitCode, 106);
      }
    }
  } finally {
    await curve.terminate();
  }
});
